export const getKaithiraiPattuCollection = (slug) =>
  kaithiraiPattuCollections.find((c) => c.slug === slug || c.altSlugs?.includes(slug))

export const getKaithiraiPattuDesign = (collectionSlug, designSlug) => {
  const collection = getKaithiraiPattuCollection(collectionSlug)
  return collection?.designs.find((d) => d.slug === designSlug || d.altSlugs?.includes(designSlug))
}
