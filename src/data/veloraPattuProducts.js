export const getVeloraPattuCollection = (slug) =>
  veloraPattuCollections.find((c) => c.slug === slug || c.altSlugs?.includes(slug))

export const getVeloraPattuDesign = (collectionSlug, designSlug) => {
  const collection = getVeloraPattuCollection(collectionSlug)
  return collection?.designs.find((d) => d.slug === designSlug || d.altSlugs?.includes(designSlug))
}
